import { defineField, defineType } from 'sanity'

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Site settings',
  type: 'document',
  groups: [
    { name: 'store', title: 'Store', default: true },
    { name: 'home', title: 'Home page' },
    { name: 'delivery', title: 'Delivery and returns' },
    { name: 'contact', title: 'Contact' },
    { name: 'pages', title: 'Policy pages' },
    { name: 'ads', title: 'Ads tracking' },
  ],
  fields: [
    defineField({
      name: 'storeName',
      title: 'Store name',
      type: 'string',
      group: 'store',
      initialValue: 'Vastre',
      validation: (r) => r.required().max(40),
    }),
    defineField({
      name: 'tagline',
      title: 'Tagline',
      type: 'string',
      group: 'store',
      description: 'A few words shown in the footer and in Google results, e.g. "Ladies\' eastern wear".',
      validation: (r) => r.max(60),
    }),
    defineField({
      name: 'announcement',
      title: 'Top banner',
      type: 'string',
      group: 'store',
      description: 'A thin line at the very top of every page, e.g. "Free delivery over Rs. 6,000". Leave empty to hide it.',
      validation: (r) => r.max(90),
    }),

    defineField({
      name: 'heroHeadline',
      title: 'Home page headline',
      type: 'string',
      group: 'home',
      validation: (r) => r.required().max(70),
    }),
    defineField({ name: 'heroText', title: 'Home page text under the headline', type: 'text', rows: 3, group: 'home', validation: (r) => r.max(200) }),
    defineField({
      name: 'heroImage',
      title: 'Home page photo',
      type: 'image',
      group: 'home',
      description: 'Shown inside the arch at the top of the home page. A tall photo of a model wearing your best piece works best.',
      options: { hotspot: true },
      fields: [defineField({ name: 'alt', title: 'Short description of the photo', type: 'string' })],
    }),
    defineField({ name: 'heroButton', title: 'Main button text', type: 'string', group: 'home', initialValue: 'Shop new arrivals', validation: (r) => r.required().max(30) }),

    defineField({
      name: 'deliveryFee',
      title: 'Delivery charge (Rs.)',
      type: 'number',
      group: 'delivery',
      description: 'Enter 0 for free delivery on every order.',
      validation: (r) => r.required().integer().min(0),
    }),
    defineField({
      name: 'freeDeliveryOver',
      title: 'Free delivery on orders above (Rs.)',
      type: 'number',
      group: 'delivery',
      description: 'Optional. Orders at or above this amount get free delivery. Leave empty if there is no such offer.',
      validation: (r) => r.integer().min(0),
    }),
    defineField({ name: 'deliveryTime', title: 'Delivery time', type: 'string', group: 'delivery', description: 'e.g. "Delivered in 3 to 5 working days". Only promise what you can keep.' }),
    defineField({ name: 'returnSummary', title: 'Returns and exchanges, one line', type: 'string', group: 'delivery', description: 'e.g. "Size exchange within 7 days of delivery".' }),
    defineField({ name: 'codNote', title: 'Cash on delivery note', type: 'string', group: 'delivery', description: 'e.g. "Pay the rider in cash when your parcel arrives."' }),
    defineField({
      name: 'sizeChart',
      title: 'Size chart image',
      type: 'image',
      group: 'delivery',
      description: 'A picture of your size chart with measurements. It appears on product pages that have sizes.',
      fields: [defineField({ name: 'alt', title: 'Short description', type: 'string' })],
    }),

    defineField({
      name: 'whatsappNumber',
      title: 'WhatsApp number',
      type: 'string',
      group: 'contact',
      description: 'With country code, digits only, no plus or spaces. Example: 923001234567',
      validation: (r) => r.required().regex(/^92\d{10}$/, { name: 'Pakistan number', invert: false }).error('Use the format 923001234567 (92, then the 10 digits without the leading 0).'),
    }),
    defineField({ name: 'instagram', title: 'Instagram username', type: 'string', group: 'contact', description: 'Without the @, e.g. vastre.pk' }),
    defineField({ name: 'email', title: 'Email address (optional)', type: 'string', group: 'contact', validation: (r) => r.email() }),

    defineField({ name: 'aboutText', title: 'About us', type: 'text', rows: 8, group: 'pages', description: 'Your brand story. Leave empty to hide the About page.' }),
    defineField({ name: 'deliveryPolicy', title: 'Delivery policy', type: 'text', rows: 8, group: 'pages', description: 'Leave empty to hide the Delivery page.' }),
    defineField({ name: 'returnPolicy', title: 'Return and exchange policy', type: 'text', rows: 8, group: 'pages', description: 'Leave empty to hide the Returns page.' }),
    defineField({
      name: 'privacyPolicy',
      title: 'Privacy policy',
      type: 'text',
      rows: 8,
      group: 'pages',
      description: 'Leave empty to use the built-in starting text. Read it before launch and change anything that does not match how you work.',
    }),

    defineField({
      name: 'metaPixelId',
      title: 'Meta Pixel ID',
      type: 'string',
      group: 'ads',
      description: 'From Meta Events Manager. Digits only. This lets Facebook and Instagram ads measure orders from the site.',
      validation: (r) => r.regex(/^\d{5,20}$/, { name: 'digits only' }).error('The Pixel ID is digits only.'),
    }),
  ],
  preview: { prepare: () => ({ title: 'Site settings' }) },
})
